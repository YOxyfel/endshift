#!/usr/bin/env node
/**
 * npm run fonts: download Sofia Sans + Sofia Sans Extra Condensed (OFL) from Google Fonts
 * and self-host them in src/assets/fonts/. After this, the site makes no request to Google.
 * Only the Latin, Latin Extended, Cyrillic and Cyrillic Extended subsets are kept.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/assets/fonts');
const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Sofia+Sans+Extra+Condensed:wght@500..900&family=Sofia+Sans:ital,wght@0,300..750;1,400..600&display=swap';
// A modern browser user agent makes Google return woff2 files with unicode-range subsets.
const UA = 'Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const KEEP = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
if (!css.includes('@font-face')) throw new Error('Google Fonts returned no @font-face rules. Check your connection.');

await mkdir(OUT, { recursive: true });
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)];
let outCss = '/* Sofia Sans and Sofia Sans Extra Condensed by Lettersoup. SIL Open Font License 1.1. Generated by scripts/fetch-fonts.mjs */\n';
let n = 0;
for (const [, subset, block] of blocks) {
  if (!KEEP.includes(subset)) continue;
  const family = block.match(/font-family:\s*'([^']+)'/)[1];
  const style = block.match(/font-style:\s*(\w+)/)[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const name = `${family.toLowerCase().replace(/\s+/g, '-')}${style === 'italic' ? '-italic' : ''}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  await writeFile(path.join(OUT, name), buf);
  outCss += `/* ${subset} */\n${block.replace(/url\([^)]+\)/, `url('./${name}')`)}\n`;
  n++;
  console.log(`  ${name}  ${(buf.length / 1024).toFixed(1)} KB`);
}
await writeFile(path.join(OUT, 'fonts.css'), outCss);
console.log(`\nSaved ${n} font files to src/assets/fonts/. Rebuild with npm run build.`);
