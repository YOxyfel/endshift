// minute marker + full-length seconds, used by the step list, the home preview and the dial
const withMarkers = (steps) => {
  let acc = 0;
  return steps.map((s) => {
    const out = { ...s, minute: Math.round(acc / 60), duration: s.seconds.full };
    acc += s.seconds.full;
    return out;
  });
};

